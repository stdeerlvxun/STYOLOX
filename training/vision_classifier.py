def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def training_exclusion_reason(label, has_draft=False):
    # "defect" is generated by selecting problem points; it is not a state-button choice.
    if label.get('image_state', '') not in {'', 'defect'}:
        return 'image_state_selected'
    if not label.get('defects'):
        return 'missing_problem_labels'
    if has_draft:
        return 'unconfirmed_edit'
    return ''


def validate_training_dataset(dataset):
    if dataset.get('training_policy') != TRAINING_POLICY:
        raise ValueError('Dataset uses the superseded image-state training policy; prepare a new problem-only run')
    if not dataset.get('records'):
        raise ValueError('No confirmed problem-point images are available')
    for row in dataset['records']:
        reason = training_exclusion_reason(row, row.get('has_draft', False))
        if reason:
            raise ValueError('Ineligible training image: ' + str(row['image_id']) + ' (' + reason + ')')


class Groups:
    def __init__(self, n):
        self.parents = list(range(n))

    def find(self, a):
        while self.parents[a] != a:
            self.parents[a] = self.parents[self.parents[a]]
            a = self.parents[a]
        return a

    def union(self, a, b):
        self.parents[self.find(a)] = self.find(b)


def assign_groups(records):
    """Keep linked production orders, cases and repeated/near-repeated images together."""
    groups, seen = Groups(len(records)), {}
    for i, row in enumerate(records):
        for key in ['case:' + row['case_id'], 'sha:' + row['sha256']] + ['order:' + v for v in row['order_keys']]:
            if key in seen:
                groups.union(i, seen[key])
            else:
                seen[key] = i
        for j in range(i):
            other = records[j]
            # Conservative pHash grouping; grouping does not delete either photo.
            if abs(row['aspect'] / other['aspect'] - 1) < .03 and (row['phash'] ^ other['phash']).bit_count() <= 2:
                groups.union(i, j)
    for i, row in enumerate(records):
        row['group'] = groups.find(i)


def split_groups(records, seed=42):
    grouped = defaultdict(list)
    for row in records:
        grouped[row['group']].append(row)
    if len(grouped) < 8:
        raise ValueError('Too few independent order groups for a train/validation/test split')
    labels = lambda row: ['problem:' + x for x in row['defects']]
    totals = Counter(label for row in records for label in labels(row))
    targets = {'train': .70, 'validation': .15, 'test': .15}
    rng, best = random.Random(seed), None
    # Choose a stratified split using labels only, before training or scoring models.
    for _ in range(500):
        assignments = {key: rng.choices(list(targets), weights=list(targets.values()))[0] for key in sorted(grouped)}
        counts = {part: Counter() for part in targets}
        for key, rows in grouped.items():
            for row in rows:
                counts[assignments[key]].update(labels(row) + ['all'])
        score = sum(((counts[p]['all'] / len(records) - fraction) / fraction) ** 2 for p, fraction in targets.items())
        for label, total in totals.items():
            if counts['train'][label] == 0:
                score += 1000
            if total >= 5:
                for part, fraction in targets.items():
                    score += ((counts[part][label] / total - fraction) ** 2) / max(fraction, .15)
        if best is None or score < best[0]:
            best = (score, assignments)
    for row in records:
        row['split'] = best[1][row['group']]
    for key in grouped:
        assert len({r['split'] for r in records if r['group'] == key}) == 1
    if any(not any(r['split'] == 'train' and problem in r['defects'] for r in records)
           for problem in {x for r in records for x in r['defects']}):
        raise ValueError('Could not retain every problem category in training without splitting linked groups')


def prepare(run, source_root):
    target = run / 'dataset.json'
    if target.exists():
        raise ValueError('Dataset is already frozen; use a new run directory for a new label snapshot')
    db_path = run / 'source' / 'labels.sqlite3'
    with closing(sqlite3.connect(db_path.resolve().as_uri() + '?mode=ro', uri=True)) as db:
        db.row_factory = sqlite3.Row
        rows = [dict(r) for r in db.execute('SELECT i.id AS image_id,i.relative_path,i.case_id,l.data,l.updated_at,'
               'd.image_id IS NOT NULL AS has_draft FROM labels l JOIN images i ON i.id=l.image_id '
               'LEFT JOIN drafts d ON d.image_id=i.id ORDER BY i.id')]
    excluded, candidates, metadata = [], [], {}
    for row in rows:
        label = json.loads(row.pop('data'))
        reason = training_exclusion_reason(label, row['has_draft'])
        if reason:
            excluded.append({'image_id': row['image_id'], 'reason': reason})
            continue
        relative = Path(row['relative_path'])
        if relative.is_absolute() or '..' in relative.parts:
            raise ValueError('Invalid source path')
        path = source_root / relative
        case_path = path.parent.parent.parent / 'case.json'
        try:
            raw = path.read_bytes()
            with Image.open(io.BytesIO(raw)) as original:
                image = ImageOps.exif_transpose(original).convert('RGB')
                width, height = image.size
                gray = np.asarray(image.convert('L').resize((32, 32)), dtype=np.float32)
            dct = cv2.dct(gray)[:8, :8].flatten()[1:]
            phash = sum(int(value > np.median(dct)) << bit for bit, value in enumerate(dct))
            if case_path not in metadata:
                metadata[case_path] = read_json(case_path)
            case = metadata[case_path]
            order_keys = []
            for order in case.get('related_orders', []):
                for field in ['h3_object_id', 'production_no', 'crm_no', 'contract_no']:
                    if order.get(field):
                        order_keys.append(field + ':' + str(order[field]).strip())
            order_keys += ['h3_object_id:' + str(v) for v in case.get('order_link', {}).get('ids', []) if v]
            candidates.append({**row, 'full_path': str(path), 'sha256': hashlib.sha256(raw).hexdigest(),
                'width': width, 'height': height, 'aspect': width / height, 'phash': phash,
                'order_keys': sorted(set(order_keys)), 'image_state': label['image_state'],
                'defects': label['defects'], 'responsibilities': label['responsibilities']})
        except (OSError, ValueError, KeyError) as exc:
            excluded.append({'image_id': row['image_id'], 'reason': 'source_error', 'error': str(exc)})
    by_sha = defaultdict(list)
    for row in candidates:
        by_sha[row['sha256']].append(row)
    records = []
    for duplicates in by_sha.values():
        labels = {(r['image_state'], tuple(sorted(r['defects']))) for r in duplicates}
        if len(labels) > 1:
            excluded.extend({'image_id': r['image_id'], 'reason': 'conflicting_duplicate_labels'} for r in duplicates)
            continue
        kept = duplicates[0]
        kept['alias_image_ids'] = [r['image_id'] for r in duplicates[1:]]
        kept['order_keys'] = sorted({v for r in duplicates for v in r['order_keys']} |
                                    {'case_alias:' + r['case_id'] for r in duplicates})
        records.append(kept)
        excluded.extend({'image_id': r['image_id'], 'reason': 'exact_duplicate'} for r in duplicates[1:])
    assign_groups(records)
    split_groups(records)
    for row in records:
        row.pop('phash')
    train = [row for row in records if row['split'] == 'train']
    problem_counts = Counter(x for row in train for x in row['defects'])
    all_counts = Counter(x for row in records for x in row['defects'])
    problems = sorted(all_counts)
    counts = {part: {'images': sum(r['split'] == part for r in records),
                    'groups': len({r['group'] for r in records if r['split'] == part}),
                    'states': dict(Counter(r['image_state'] for r in records if r['split'] == part)),
                    'problems': dict(Counter(x for r in records if r['split'] == part for x in r['defects']))}
              for part in ['train', 'validation', 'test']}
    summary = {'snapshot_confirmed': len(rows), 'usable_unique_images': len(records), 'splits': counts,
               'problem_classes': problems, 'all_problem_counts': all_counts,
               'scarce_training_classes': {name: count for name, count in problem_counts.items() if count < 5},
               'excluded_reasons': dict(Counter(x['reason'] for x in excluded)),
               'sparse_problem_policy': 'Include every problem category, including one-sample classes; flag scarcity without excluding it',
               'image_state_policy': 'Any image-state button selection is excluded from train, validation and test; no state classifier',
               'split_policy': '70/15/15 target; group by case, linked order identifiers and exact/near duplicates',
               'responsibility_policy': 'Not learned from pixels; only user-approved rules map candidate problems to defaults'}
    dataset = {'schema_version': 2, 'training_policy': TRAINING_POLICY,
               'created_at': dt.datetime.now(dt.timezone.utc).isoformat(),
               'seed': 42, 'source_root': str(source_root), 'snapshot_sha256': hashlib.sha256(db_path.read_bytes()).hexdigest(),
               'summary': summary, 'records': records, 'excluded': excluded}
    validate_training_dataset(dataset)
    write_json(target, dataset)
    write_json(run / 'data-summary.json', summary)
    print(json.dumps(summary, ensure_ascii=False), flush=True)


def load_backbone(device):
    from yolox.exp import get_exp
    meta = read_json(WORK / 'models' / 'YOLOX-s' / 'model.json')
    checkpoint = WORK / 'models' / 'YOLOX-s' / 'yolox_s.pth'
    actual_hash = hashlib.sha256(checkpoint.read_bytes()).hexdigest()
    if actual_hash != meta['sha256']:
        raise ValueError('Base model checksum changed')
    exp = get_exp(str(WORK / 'models' / 'YOLOX-s' / 'yolox_s.py'), None)
    model = exp.get_model()
    model.load_state_dict(torch.load(checkpoint, map_location='cpu', weights_only=False)['model'], strict=True)
    backbone = model.backbone.eval().to(device).float()
    for parameter in backbone.parameters():
        parameter.requires_grad_(False)
    return backbone, actual_hash


def image_tensor(row, size):
    from yolox.data.data_augment import preproc
    raw = Path(row['full_path']).read_bytes()
    if hashlib.sha256(raw).hexdigest() != row['sha256']:
        raise ValueError('Source image changed after snapshot: ' + str(row['image_id']))
    with Image.open(io.BytesIO(raw)) as image:
        image = np.asarray(ImageOps.exif_transpose(image).convert('RGB'))[:, :, ::-1].copy()
    return torch.from_numpy(preproc(image, (size, size))[0])


def features(backbone, inputs):
    maps = backbone(inputs)
    return torch.cat([pooled.flatten(1) for feature in maps for pooled in
                      [F.adaptive_avg_pool2d(feature, 1), F.adaptive_max_pool2d(feature, 1)]], dim=1)


def extract(run, dataset, size=640, batch=2):
    cache = run / 'features.pt'
    manifest_hash = hashlib.sha256((run / 'dataset.json').read_bytes()).hexdigest()
    if cache.exists():
        data = torch.load(cache, map_location='cpu', weights_only=True)
        if data['manifest_hash'] != manifest_hash or data['input_size'] != size:
            raise ValueError('Feature cache does not match this frozen dataset')
        return data
    started = time.perf_counter()
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    torch.set_num_threads(4)
    if device.type == 'cuda':
        torch.cuda.reset_peak_memory_stats()
    backbone, base_hash = load_backbone(device)
    rows, output = dataset['records'], []
    with ThreadPoolExecutor(max_workers=2) as pool, torch.inference_mode():
        for start in range(0, len(rows), batch):
            inputs = torch.stack(list(pool.map(lambda row: image_tensor(row, size), rows[start:start + batch]))).to(device)
            output.append(features(backbone, inputs).cpu())
            if (start // batch) % 10 == 0 or start + batch >= len(rows):
                progress = {'stage': 'features', 'done': min(start + batch, len(rows)), 'total': len(rows),
                            'elapsed_seconds': round(time.perf_counter() - started, 1)}
                write_json(run / 'progress.json', progress)
                print(json.dumps(progress), flush=True)
    info = {'device': str(device), 'seconds': round(time.perf_counter() - started, 2),
            'peak_allocated_mib': round(torch.cuda.max_memory_allocated() / 2**20, 1) if device.type == 'cuda' else None}
    result = {'features': torch.cat(output), 'manifest_hash': manifest_hash, 'base_sha256': base_hash,
              'input_size': size, 'feature_extraction': info}
    torch.save(result, cache)
    del backbone
    if device.type == 'cuda':
        torch.cuda.empty_cache()
    return result


def confusion_metrics(actual, predicted, classes):
    matrix = np.zeros((len(classes), len(classes)), dtype=np.int64)
    for true, guess in zip(actual, predicted):
        matrix[true, guess] += 1
    per_class = []
    for i, name in enumerate(classes):
        tp, support, guesses = int(matrix[i, i]), int(matrix[i].sum()), int(matrix[:, i].sum())
        precision, recall = tp / guesses if guesses else 0., tp / support if support else None
        per_class.append({'class': name, 'support': support, 'precision': precision, 'recall': recall,
                          'f1': 2 * precision * recall / (precision + recall) if recall is not None and precision + recall else 0.})
    return {'accuracy': float(np.trace(matrix) / max(1, matrix.sum())), 'per_class': per_class,
            'confusion_rows_actual_columns_predicted': matrix.tolist()}


def problem_metrics(actual, scores, classes):
    result = []
    for i, name in enumerate(classes):
        truth, guess = actual[:, i].astype(bool), scores[:, i] >= .5
        tp, fp, fn = int((truth & guess).sum()), int((~truth & guess).sum()), int((truth & ~guess).sum())
        precision, recall = tp / (tp + fp) if tp + fp else 0., tp / (tp + fn) if tp + fn else None
        result.append({'class': name, 'support': int(truth.sum()), 'tp': tp, 'fp': fp, 'fn': fn,
                       'precision': precision, 'recall': recall,
                       'f1': 2 * precision * recall / (precision + recall) if recall is not None and precision + recall else 0.})
    return result


def train(run, epochs=250, balanced_init=False):
    dataset = read_json(run / 'dataset.json')
    validate_training_dataset(dataset)
    cache = extract(run, dataset)
    torch.manual_seed(dataset['seed'])
    rows, problems = dataset['records'], dataset['summary']['problem_classes']
    raw = cache['features'].float()
    masks = {part: torch.tensor([row['split'] == part for row in rows]) for part in ['train', 'validation', 'test']}
    mean, std = raw[masks['train']].mean(0), raw[masks['train']].std(0).clamp_min(.05)
    x = (raw - mean) / std
    yp = torch.tensor([[float(name in row['defects']) for name in problems] for row in rows])
    if not problems or any(not masks[p].any() for p in masks):
        raise ValueError('Problem categories and non-empty grouped train/validation/test splits are required')
    problem_head = nn.Linear(x.shape[1], len(problems))
    positives = yp[masks['train']].sum(0)
    if (positives == 0).any():
        raise ValueError('Every included problem category needs a positive training example')
    negatives = masks['train'].sum() - positives
    pos_weight = (negatives / positives).clamp(1, 10)
    if balanced_init:
        # Use training counts only: the constant-logit optimum of weighted BCE.
        nn.init.normal_(problem_head.weight, mean=0., std=.002)
        with torch.no_grad():
            problem_head.bias.copy_(torch.log(positives * pos_weight / negatives.clamp_min(1)))
    initial = problem_head.weight.detach().clone()
    learning_rate = .0005 if balanced_init else .003
    training_config = {'balanced_init': balanced_init, 'learning_rate': learning_rate, 'weight_decay': .05}
    problem_loss = nn.BCEWithLogitsLoss(pos_weight=pos_weight)
    optimizer = torch.optim.AdamW(problem_head.parameters(), lr=learning_rate, weight_decay=.05)

    def loss(part):
        mask = masks[part]
        return problem_loss(problem_head(x[mask]), yp[mask])

    best, best_epoch, stale, history = float('inf'), 0, 0, []
    started = time.perf_counter()
    for epoch in range(1, epochs + 1):
        optimizer.zero_grad()
        training = loss('train')
        if not torch.isfinite(training):
            raise ValueError('Non-finite training loss')
        training.backward()
        nn.utils.clip_grad_norm_(problem_head.parameters(), 5)
        optimizer.step()
        with torch.no_grad():
            validation = float(loss('validation'))
        history.append({'epoch': epoch, 'train_loss': float(training.detach()), 'validation_loss': validation})
        if validation < best - .0001:
            best, best_epoch, stale = validation, epoch, 0
            best_problem = copy.deepcopy(problem_head.state_dict())
        else:
            stale += 1
        if epoch % 10 == 0:
            print(json.dumps(history[-1]), flush=True)
        if stale >= 30:
            break
    problem_head.load_state_dict(best_problem)
    checkpoint = {'schema_version': 2, 'training_policy': TRAINING_POLICY, 'problem_state_dict': best_problem,
                  'training_config': training_config,
                  'feature_mean': mean, 'feature_std': std, 'problems': problems,
                  'base_sha256': cache['base_sha256'], 'input_size': cache['input_size'],
                  'manifest_hash': cache['manifest_hash'], 'best_epoch': best_epoch, 'rules': RULES}
    torch.save(checkpoint, run / 'classifier.pt')
    report = {'status': 'experimental_completed', 'training_policy': TRAINING_POLICY,
              'training_config': training_config,
              'dataset': dataset['summary'], 'best_epoch': best_epoch,
              'epochs_run': epoch, 'training_seconds': round(time.perf_counter() - started, 2),
              'feature_extraction': cache['feature_extraction'],
              'weights_changed_l2': float((problem_head.weight.detach() - initial).norm()),
              'input_size': cache['input_size'], 'base_sha256': cache['base_sha256'],
              'threshold': .5, 'probabilities_calibrated': False, 'production_ready': False,
              'method': 'Frozen YOLOX-s features + problem-point multilabel classifier only; no image-state gate',
              'limitations': ['Small samples included; scarcity does not imply reliable recognition', 'Image-state samples are excluded; no state or healthy-board classifier',
                             'Image-level labels only; no bounding-box detector', 'Responsibility is not learned',
                             'Test set is grouped by order and duplicates; small support remains uncertain']}
    with torch.inference_mode():
        issue_scores = problem_head(x).sigmoid().numpy()
    predictions = []
    for part in ['train', 'validation', 'test']:
        mask = masks[part].numpy()
        report[part] = {'problems': problem_metrics(yp.numpy()[mask], issue_scores[mask], problems)}
    for i, row in enumerate(rows):
        if row['split'] == 'test':
            predicted_problems = [name for j, name in enumerate(problems) if issue_scores[i, j] >= .5]
            predictions.append({'image_id': row['image_id'], 'relative_path': row['relative_path'],
                                'true_problems': row['defects'], 'candidate_problems': predicted_problems,
                                'problem_scores': dict(zip(problems, map(float, issue_scores[i])))})
    write_json(run / 'metrics.json', report)
    write_json(run / 'training-history.json', history)
    write_json(run / 'test-predictions.json', predictions)
    write_json(run / 'progress.json', {'stage': 'completed', 'model': str(run / 'classifier.pt'), 'best_epoch': best_epoch})
    print(json.dumps({'status': report['status'], 'model': str(run / 'classifier.pt'), 'test': report['test']}, ensure_ascii=False), flush=True)


def predict(run, image_path, output):
    checkpoint = torch.load(run / 'classifier.pt', map_location='cpu', weights_only=True)
    if checkpoint.get('classifier_kind') in {'centered_kernel_ridge', 'corrected_yolox_head', 'convnext_mil_finetuned'}:
        from improve_classifier import predict as predict_improved
        return predict_improved(run, image_path, output)
    if checkpoint.get('training_policy') != TRAINING_POLICY:
        raise ValueError('This model used excluded image-state samples and is superseded; train a problem-only model first')
    raw = image_path.read_bytes()
    row = {'image_id': 'external', 'full_path': str(image_path), 'sha256': hashlib.sha256(raw).hexdigest()}
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    torch.set_num_threads(4)
    backbone, base_hash = load_backbone(device)
    if base_hash != checkpoint['base_sha256']:
        raise ValueError('Inference backbone differs from the training backbone')
    start = time.perf_counter()
    with torch.inference_mode():
        vector = features(backbone, image_tensor(row, checkpoint['input_size']).unsqueeze(0).to(device)).cpu()
        vector = (vector - checkpoint['feature_mean']) / checkpoint['feature_std']
        problems = checkpoint['problems']
        if problems:
            problem_head = nn.Linear(vector.shape[1], len(problems))
            problem_head.load_state_dict(checkpoint['problem_state_dict'])
            problem_scores = problem_head(vector).sigmoid()[0].tolist()
        else:
            problem_scores = []
    candidates = [name for name, score in zip(problems, problem_scores) if score >= .5]
    result = {'image': str(image_path), 'sha256': row['sha256'], 'training_policy': TRAINING_POLICY,
              'candidate_problems': candidates,
              'problem_scores': dict(zip(problems, problem_scores)), 'requires_human_review': True,
              'objective': 'find_problem_points_for_human_review',
              'normal_state_supported': False, 'elapsed_seconds_excluding_model_load': round(time.perf_counter() - start, 3)}
    write_json(output, result)
    print(json.dumps(result, ensure_ascii=False, indent=2), flush=True)


